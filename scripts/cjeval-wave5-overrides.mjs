export function applyWave5Overrides(q) {
  const fn = WAVE5_ITEM_OVERRIDES[q.id];
  if (fn) {
    fn(q);
  }
  const fn7 = WAVE7_ITEM_OVERRIDES[q.id];
  if (fn7) {
    fn7(q);
  }

  // Convert paragraph 1's （1） or (1) before ② into ① when the passage uses ②, ③...
  if (q.stem && q.stem.includes("②") && q.stem.includes("③")) {
    const idx2 = q.stem.indexOf("②");
    const before2 = q.stem.slice(0, idx2);
    if (!before2.includes("①") && !/[（(]2[）)]/u.test(before2) && /[（(]1[）)]/u.test(before2)) {
      q.stem = q.stem.replace(/[（(]1[）)]\s*/u, "\n\n① ");
    }
  }

  // When a reading passage uses circled paragraph markers ①..⑳, normalize 第（4）段 / 第(1)自然段 -> 第④段 / 第①自然段
  const usesCircledParas =
    /[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]/u.test(q.stem) &&
    !/（2）[^\n]{10,}\n+（3）/u.test(q.stem);
  const replaceParaRefs = (s) =>
    usesCircledParas
      ? String(s ?? "").replace(/第\s*[（(](\d{1,2})[）)]\s*((?:自然)?段)/gu, (m, d, unit) => {
          const c = WAVE7_CIRCLED[Number(d) - 1];
          return c ? `第${c}${unit}` : m;
        })
      : String(s ?? "");

  const cleanPunct = (s) =>
    replaceParaRefs(s)
      .replace(/[Ａ-Ｚａ-ｚ０-９]/gu, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xfee0))
      .replace(/【+/gu, "【")
      .replace(/】+/gu, "】")
      .replace(/\s*•\s*/gu, "·")
      // Wave 12 (Round 5): Split glued poem title/author/first-verse headers
      .replace(/送友人李白青山横北郭/gu, "送友人\n李白\n青山横北郭")
      .replace(/破阵子·为陈同甫赋壮词以寄之辛弃疾醉里挑灯看剑/gu, "破阵子·为陈同甫赋壮词以寄之\n辛弃疾\n醉里挑灯看剑")
      .replace(/水调歌头苏轼丙辰中秋/gu, "水调歌头\n苏轼\n丙辰中秋")
      .replace(/渡荆门送别李白渡远荆门外/gu, "渡荆门送别\n李白\n渡远荆门外")
      .replace(/江城子·密州出猎苏轼老夫聊发少年狂/gu, "江城子·密州出猎\n苏轼\n老夫聊发少年狂")
      .replace(/早春呈水部张十八员外韩愈天街小雨润如酥/gu, "早春呈水部张十八员外\n韩愈\n天街小雨润如酥")
      .replace(/次北固山下王湾客路青山外/gu, "次北固山下\n王湾\n客路青山外")
      // Join mid-sentence 【甲】/【乙】/【丙】/【丁】 references broken onto separate lines
      .replace(/\n+【([甲乙丙丁])】\n+(?=[诗文词曲段篇句中两]|——|【[甲乙丙丁]】)/gu, "【$1】")
      .replace(/(?<=[在从与和及或读析讨入文])\n+【([甲乙丙丁])】\n+/gu, "【$1】")
      .replace(/"([^"\n]+)"/gu, "“$1”")
      .replace(/（([^（）()\n]+)\)/gu, "（$1）")
      .replace(/\(([^（）()\n]+)）/gu, "（$1）")
      .replace(/([，。；：、])\1+/gu, "$1")
      .replace(/？？+/gu, "？")
      .replace(/，。/gu, "。")
      .replace(/。，/gu, "，")
      .replace(/([。！？])；/gu, "$1")
      .replace(/；。/gu, "。")
      .replace(/；，/gu, "；")
      .replace(/，；/gu, "；")
      .replace(/；：/gu, "：")
      .replace(/：；/gu, "；")
      .replace(/，：/gu, "：")
      .replace(/：，/gu, "：")
      .replace(/？：/gu, "？")
      .replace(/，\.{3,}/gu, "……")
      .replace(/([。！？])[,;.:]/gu, "$1")
      .replace(/([，、；：])[,;.:]/gu, "$1")
      .replace(/[,;.:]([，。；：、！？])/gu, "$1")
      .split("\n")
      .map((line) => {
        let out = line;
        const sCount = (out.match(/['‘’]/gu) || []).length;
        if (sCount > 0 && sCount % 2 === 0) {
          let sOpen = true;
          out = out.replace(/['‘’]/gu, () => {
            const ch = sOpen ? "‘" : "’";
            sOpen = !sOpen;
            return ch;
          });
        }
        const qCount = (out.match(/[“”]/gu) || []).length;
        if (qCount > 0 && qCount % 2 === 0 && !/“[‘']/u.test(out)) {
          let open = true;
          out = out.replace(/[“”]/gu, () => {
            const ch = open ? "“" : "”";
            open = !open;
            return ch;
          });
        }
        return out;
      })
      .join("\n");
  q.stem = cleanPunct(q.stem);
  q.answer = cleanPunct(q.answer)
    .replace(/(^|\n)（([1-9]\d*)）[：:]\s*/gu, "$1（$2）");
  if (/^1\.\s+[\s\S]*?\s+2\.\s+/u.test(q.answer)) {
    q.answer = q.answer
      .replace(/^1\.\s*/u, "（1）")
      .replace(/\s+([2-9]\d*)\.\s*/gu, "\n（$1）");
  }
  if (q.options && typeof q.options === "object") {
    for (const k of Object.keys(q.options)) {
      q.options[k] = cleanPunct(q.options[k]);
    }
  }
  if (Array.isArray(q.solutions)) {
    q.solutions = q.solutions.map(cleanPunct);
  }
}
