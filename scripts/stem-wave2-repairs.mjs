const TRAILING_STRIPPED_BLANK_RE = /\s+((?:厘米|米|分米|毫米|千米|平方厘米|平方米|平方分米|公顷|立方厘米|立方分米|立方米|升|毫升|克|千克|吨|秒|分|小时|时|天|元|角|度|°|′|″|个|只|条|次|倍|人|件|箱|棵|本|支|辆|架|种|项|号|象限角|条件)?\s*[.．。])$/;

const LEADING_STEM_HEADER_RE = /^(?:[（(]\s*(?:\d{4}\s*[•·．.]\s*[^）)\d]{1,20}|[\d.]+分|[一二三四五六七八九十]+)\s*[)）]\s*|【[^】]{2,15}】\s*|\d{1,2}\s*[.．、]\s*(?=[（(【\u4e00-\u9fa5A-Za-z]))+/;

const TRAILING_NEXT_QUESTION_IN_SOLUTION_RE = /\s+(?:(?:\d{1,2}|[一二三四五六七八九十]+)\s*[.．、]\s*)?[（(]\s*(?:\d{4}\s*[•·．.]|\d+(?:\.\d+)?\s*分)[^）)]*[)）][^\n]*$/;

export function applyWave2StemNormalization(question) {
  const override = WAVE2_ITEM_OVERRIDES.get(question.id);
  if (override) {
    if (override.type) question.type = override.type;
    if (override.stem) question.stem = override.stem;
    if (override.answer) question.answer = override.answer;
    if (override.solutions) question.solutions = [...override.solutions];
  }

  // Strip leading exam headers / score prefixes / item numbers from stem
  question.stem = question.stem
    .replace(/^\$\$\\rm\{\(?(\d+)\s*分?\)?[、.．]?}\$\$\s*/, "")
    .replace(LEADING_STEM_HEADER_RE, "")
    .trim();

  // Strip leaked next-question headers at the tail of solutions
  question.solutions = (question.solutions ?? []).map((sol) =>
    String(sol ?? "")
      .replace(TRAILING_NEXT_QUESTION_IN_SOLUTION_RE, "")
      .replace(/故答为/g, "故答案为")
      .trim()
  );

  // Clean score tags from tags[]
  if (Array.isArray(question.tags)) {
    question.tags = question.tags.filter((tag) => !/^\d+(?:\.\d+)?分$/.test(String(tag).trim()));
  }

  // Restore single trailing stripped blank on short-answer的计算题/解答题/单空题/综合题 and reclassify as 填空题
  if (
    !["单选题", "多选题", "选择题", "双选题", "不定项选择题", "判断题"].includes(question.type) &&
    !question.stem.includes("_") &&
    !/[（(]\s*[)）]/.test(question.stem) &&
    question.answer.length <= 30 &&
    !/[∴∵答证明解]/.test(question.answer) &&
    TRAILING_STRIPPED_BLANK_RE.test(question.stem)
  ) {
    question.stem = question.stem.replace(TRAILING_STRIPPED_BLANK_RE, "______$1");
    question.type = "填空题";
  }

  // Normalize redundant / non-canonical question types
  if (question.type === "选择题" || question.type === "双选题" || question.type === "不定项选择题") {
    const letters = [...new Set(String(question.answer ?? "").toUpperCase().match(/[A-E]/g) ?? [])];
    question.type = letters.length > 1 || question.type === "双选题" || question.type === "不定项选择题"
      ? "多选题"
      : "单选题";
  } else if (["单空题", "多空题", "排序题", "书写"].includes(question.type)) {
    question.type = "填空题";
  } else if (["实验题", "探究题", "实验题探究题"].includes(question.type)) {
    question.type = "实验探究题";
  } else if (question.type === "资料分析题") {
    question.type = "材料分析题";
  } else if (question.type === "其他") {
    if (question.stem.includes("_") || /[（(]\s*[)）]/.test(question.stem)) {
      question.type = "填空题";
    } else {
      question.type = "解答题";
    }
  }
}
